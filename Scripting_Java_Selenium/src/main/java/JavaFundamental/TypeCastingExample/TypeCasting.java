package JavaFundamental.TypeCastingExample;

public class TypeCasting {
    public static void main(String[] args) {
       // Explicit Type Casting
        int num1 = 100;
        System.out.println("The integer type caste to :"+ (double) num1);

        //Implicit Type Casting
        long num6 = 3089765432L;
        System.out.println("The Integer Type caste to long :"+num6);
    }
}

